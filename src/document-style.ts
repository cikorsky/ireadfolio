import type {Article,PageNumberAppearance,Settings} from './types';

export function signatureLines(article:Article):string[]{
 const signature=article.signature||article.author;
 const date=article.signedDate||article.published;
 let displayDate=date.trim();
 if(!article.signedDate){const iso=/^(\d{4})-(\d{2})-(\d{2})(?:[T\s]|$)/.exec(displayDate);if(iso)displayDate=`${iso[1]}年${Number(iso[2])}月${Number(iso[3])}日`;}
 if(displayDate&&!/^[（(].*[）)]$/.test(displayDate))displayDate=`（${displayDate}）`;
 return [signature,displayDate].filter(Boolean);
}
export function pageNumberLabel(page:number,total?:number,format:PageNumberAppearance['format']='dash'):string{
 if(format==='plain')return String(page);
 if(format==='page-total')return `第 ${page} 页${total===undefined?'':` / 共 ${total} 页`}`;
 return `— ${page} —`;
}
export function documentAppearanceVariables(s:Settings):Record<string,string|number>{
 const {metadata:m,table:t,pageNumber:p}=s.appearance;
 return {'--meta-font':m.fontFamily,'--meta-size':`${m.fontSize}px`,'--meta-weight':m.fontWeight,'--meta-style':m.fontStyle,'--meta-decoration':m.textDecoration,'--meta-color':m.color,'--meta-line':`${m.lineHeight}px`,'--meta-align':m.textAlign,'--meta-before':`${m.spaceBefore}px`,'--meta-after':`${m.spaceAfter}px`,'--meta-spacing':`${m.letterSpacing}px`,
 '--table-font':t.fontFamily,'--table-size':`${t.fontSize}px`,'--table-weight':t.fontWeight,'--table-style':t.fontStyle,'--table-line':`${t.lineHeight}px`,'--table-color':t.color,'--table-head-font':t.headerFontFamily,'--table-head-size':`${t.headerFontSize}px`,'--table-head-weight':t.headerFontWeight,'--table-head-color':t.headerColor,'--table-head-bg':t.headerBackground,'--table-border':`${t.borderWidth}px ${t.borderStyle} ${t.borderColor}`,'--table-pad-x':`${t.cellPaddingX}px`,'--table-pad-y':`${t.cellPaddingY}px`,'--table-align':t.align,'--table-width':t.width==='full'?'100%':'auto','--table-stripe':t.striped?t.stripeColor:'transparent','--table-valign':t.cellVerticalAlign,
 '--page-font':p.fontFamily,'--page-size':`${p.fontSize}px`,'--page-color':p.color,'--page-align':p.align,'--page-bottom':`${p.marginBottom}px`};
}

/** Distances are measured from the physical page bottom, in CSS px (15 twips per px).
 * The retained policy template uses a 1417-twip footer and 1984-twip body bottom margin.
 */
export function pageFooterLayout(p:PageNumberAppearance):{footerTwips:number;bottomTwips:number;lineHeightPx:number}{
 const footerTwips=Math.round(p.marginBottom*15);
 const lineHeightPx=Math.max(p.fontSize*1.2,20);
 // Keep the configured footer clear of body text, including larger fonts/distances.
 const bottomTwips=Math.max(1984,footerTwips+Math.ceil((lineHeightPx+12)*15));
 return {footerTwips,bottomTwips,lineHeightPx};
}

/** Page counters are generated by the print engine, never estimated from screen scrolling. */
export function printPageCSS(s:Settings):string{
 const p=s.appearance.pageNumber;
 const layout=pageFooterLayout(p);
 const style=document.createElement('span').style;
 for(const [key,value]of Object.entries({'font-family':p.fontFamily,'font-size':`${p.fontSize}px`,'font-weight':'400','font-style':'normal','color':p.color,'text-align':p.align,'vertical-align':'bottom','line-height':`${layout.lineHeightPx}px`,'padding-bottom':`${layout.footerTwips/15}px`}))style.setProperty(key,value);
 const counter=p.format==='plain'?'counter(page)':p.format==='page-total'?'"第 " counter(page) " 页 / 共 " counter(pages) " 页"':'"— " counter(page) " —"';
 const box=`@bottom-${p.align==='center'?'center':p.align}`;
 const firstIncrement=p.start!==1?`counter-increment:page ${p.start};`:'';
 const css=`@page{size:A4;margin:28mm 21mm ${layout.bottomTwips/15}px;counter-increment:page;${box}{content:${p.enabled?counter:'none'};${style.cssText.replace(/</g,'\\3c ')}}}@page:first{${firstIncrement}${!p.firstPage?`${box}{content:none}`:''}}`;
 return css;
}
